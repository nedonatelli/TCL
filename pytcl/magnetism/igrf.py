def _parse_igrf14_table() -> tuple[
    np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray
]:
    """Parse the embedded IAGA table into per-epoch coefficient arrays.

    Returns ``(epochs, g, h, g_sv, h_sv)`` where ``g``/``h`` have shape
    ``(n_epochs, n_max + 1, n_max + 1)`` in nT and ``g_sv``/``h_sv`` hold
    the published secular variation for the interval after the final
    epoch, in nT/year.
    """
    lines = [
        ln for ln in _IGRF14_COF.splitlines() if ln.strip() and not ln.startswith("#")
    ]
    # lines[0] labels each column's model class (IGRF/DGRF/SV); lines[1]
    # holds the epoch years, ending with the SV validity range ("2025-30")
    epochs = np.array([float(tok) for tok in lines[1].split()[3:-1]])
    n_max = 13
    n_epochs = len(epochs)
    g = np.zeros((n_epochs, n_max + 1, n_max + 1))
    h = np.zeros((n_epochs, n_max + 1, n_max + 1))
    g_sv = np.zeros((n_max + 1, n_max + 1))
    h_sv = np.zeros((n_max + 1, n_max + 1))
    for ln in lines[2:]:
        toks = ln.split()
        n, m = int(toks[1]), int(toks[2])
        vals = [float(tok) for tok in toks[3:]]
        if toks[0] == "g":
            g[:, n, m] = vals[:-1]
            g_sv[n, m] = vals[-1]
        else:
            h[:, n, m] = vals[:-1]
            h_sv[n, m] = vals[-1]
    return epochs, g, h, g_sv, h_sv


_IGRF14_EPOCHS, _IGRF14_G, _IGRF14_H, _IGRF14_G_SV, _IGRF14_H_SV = _parse_igrf14_table()


def create_igrf14_coefficients(year: Optional[float] = None) -> MagneticCoefficients:
    """
    Create IGRF-14 model coefficients for a given decimal year.

    Parameters
    ----------
    year : float, optional
        Decimal year selecting the coefficient epoch. Default is the
        IGRF-14 reference epoch, 2025.0.

    Returns
    -------
    coeffs : MagneticCoefficients
        Spherical harmonic coefficients whose linear time term reproduces
        the IGRF-14 field at ``year``. At or after 2025.0 this is the
        reference-epoch main field with the published 2025-2030 secular
        variation as ``g_dot``/``h_dot``. Within 1900.0-2025.0 it is the
        main field of the five-year epoch at or below ``year``, with the
        slope of the bracketing interval as the time term, so a field
        evaluation at ``year`` linearly interpolates the two neighboring
        epochs. Before 1900.0 the 1900-1905 slope extrapolates backwards,
        with a warning.

    Examples
    --------
    >>> coeffs = create_igrf14_coefficients()
    >>> coeffs.epoch
    2025.0
    >>> coeffs.g[1, 0]
    -29350.0
    >>> create_igrf14_coefficients(2012.5).epoch
    2010.0

    Notes
    -----
    Port of ``getIGRFCoeffs.m`` from the MATLAB library (epoch selection
    and interpolation; the Schmidt semi-normalized coefficients are kept
    in nT for :func:`pytcl.magnetism.wmm.wmm`-style evaluation rather
    than fully normalized in Tesla).

    Deviation from the MATLAB original: a warning is emitted for years
    beyond 2030.0, the end of the published secular-variation window.
    ``getIGRFCoeffs.m`` extrapolates forward silently; the IGRF-13 model
    embedded in this library previously did the same past 2025.0, and
    that silence is exactly how it went stale unnoticed.
    """
    if year is None:
        year = float(_IGRF14_EPOCHS[-1])

    first = float(_IGRF14_EPOCHS[0])
    last = float(_IGRF14_EPOCHS[-1])
    if year < first:
        warnings.warn(
            f"The year is before the first epoch ({first}) of the IGRF-14 "
            "tables; values are extrapolated backwards from the "
            "1900-1905 interval.",
            stacklevel=2,
        )
    if year > last + 5.0:
        warnings.warn(
            f"The year is beyond {last + 5.0}, the end of the IGRF-14 "
            "secular-variation validity window; treat the result as an "
            "unofficial extrapolation. For predicting the field forward "
            "prefer the current WMM.",
            stacklevel=2,
        )

    n_max = 13
    if year >= last:
        idx = len(_IGRF14_EPOCHS) - 1
        g_dot = _IGRF14_G_SV
        h_dot = _IGRF14_H_SV
    else:
        idx = max(int(np.searchsorted(_IGRF14_EPOCHS, year, side="right")) - 1, 0)
        span = _IGRF14_EPOCHS[idx + 1] - _IGRF14_EPOCHS[idx]
        g_dot = (_IGRF14_G[idx + 1] - _IGRF14_G[idx]) / span
        h_dot = (_IGRF14_H[idx + 1] - _IGRF14_H[idx]) / span

    return MagneticCoefficients(
        g=_IGRF14_G[idx].copy(),
        h=_IGRF14_H[idx].copy(),
        g_dot=g_dot.copy(),
        h_dot=h_dot.copy(),
        epoch=float(_IGRF14_EPOCHS[idx]),
        n_max=n_max,
    )


IGRF14 = create_igrf14_coefficients()


def igrf(
    lat: float,
    lon: float,
    h: float = 0.0,
    year: float = 2025.0,
    coeffs: Optional[MagneticCoefficients] = None,
) -> MagneticResult:
    """
    Compute magnetic field using IGRF model.

    Parameters
    ----------
    lat : float
        Geodetic latitude in radians.
    lon : float
        Longitude in radians.
    h : float, optional
        Height above WGS84 ellipsoid in km. Default 0.
    year : float, optional
        Decimal year. Default 2025.0, the IGRF-14 reference epoch.
    coeffs : MagneticCoefficients, optional
        Model coefficients. Default: IGRF-14 coefficients selected for
        ``year`` by :func:`create_igrf14_coefficients`, interpolating
        the 1900.0-2025.0 epoch tables and warning outside the model's
        validity window.

    Returns
    -------
    result : MagneticResult
        Magnetic field components and derived quantities.

    Examples
    --------
    >>> import numpy as np
    >>> result = igrf(np.radians(45), np.radians(-75), 0, 2023.0)
    >>> print(f"Total field: {result.F:.0f} nT")
    Total field: 53341 nT
    """
    if coeffs is None:
        coeffs = create_igrf14_coefficients(year)

    # Same geodetic evaluation as the WMM (WGS84 geodetic-to-geocentric
    # conversion, Schmidt-normalized synthesis, frame rotation). Uses the
    # unwarned core directly: IGRF coefficients carry their own validity
    # window (checked in create_igrf14_coefficients), not WMM's five-year
    # one, so wmm()'s window check does not apply here.
    return _wmm_core(lat, lon, h, year, coeffs)


